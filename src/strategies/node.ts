import path from "path";

import { config } from "../config.js";
import { buildImage, assertImageBuildsEnabled } from "./imageBuilder.js";
import type { RunDocker } from "./imageBuilder.js";
import {
  readPackageJson,
  detectPackageManager,
  installCommand,
  runScriptCommand,
} from "../packageManager.js";
import type { PackageJson, PackageManagerInfo } from "../packageManager.js";
import { testRelease } from "../test.js";
import type { BuildStrategy, LocalArtifact, StrategyInput } from "./types.js";
import type { SandboxHandle } from "../sandbox.js";

export interface NodeDockerfileInput {
  packageManager: PackageManagerInfo;
  /** Shell command run as the container's main process. */
  startCommand: string;
  port: number;
  hasBuildScript: boolean;
  nodeMajor: number;
  /** Explicit build.command, run instead of the package.json build script. */
  buildCommand?: string;
}

/** Content of the generated .dockerignore: never ship VCS data, installed modules or env files. */
export const NODE_DOCKERIGNORE = [".git", "node_modules", ".env", ".env.*", "Dockerfile*", ".dockerignore", ""].join("\n");

function installLines(pm: PackageManagerInfo, production: boolean): string {
  if (pm.name === "pnpm") {
    return `corepack pnpm install ${pm.hasLockfile ? "--frozen-lockfile" : "--no-frozen-lockfile"}${production ? " --prod" : ""}`;
  }

  if (pm.name === "yarn") {
    if (pm.yarnBerry) {
      return pm.hasLockfile
        ? `corepack yarn install --immutable${production ? " && corepack yarn workspaces focus --production" : ""}`
        : "corepack yarn install --no-immutable";
    }

    return `corepack yarn install ${pm.hasLockfile ? "--frozen-lockfile" : ""}${production ? " --production" : ""}`.replace(/ +/g, " ").trim();
  }

  return `${pm.hasLockfile ? "npm ci" : "npm install"}${production ? " --omit=dev" : ""} --no-audit --no-fund`;
}

const MANIFESTS = "package.json package-lock.json* pnpm-lock.yaml* yarn.lock* .yarnrc.yml* .npmrc*";
const SHELL_SYNTAX = /[;&|<>()$`\n\\'"*?]/;

/**
 * A deterministic multi-stage Dockerfile for a Node application. Pure: the
 * same input always yields the same text. Contains no ARG, ENV secrets or
 * build-time credentials; the app runs as the unprivileged `node` user.
 */
export function generateNodeDockerfile(input: NodeDockerfileInput): string {
  const { packageManager: pm, startCommand, port, hasBuildScript, nodeMajor } = input;

  if (!Number.isInteger(port) || port < 1 || port > 65535) {
    throw new Error(`Invalid port ${port}`);
  }

  if (!Number.isInteger(nodeMajor) || nodeMajor < 18) {
    throw new Error(`Invalid Node major version ${nodeMajor}`);
  }

  if (!startCommand.trim()) {
    throw new Error("A start command is required");
  }

  const base = `node:${nodeMajor}-alpine`;
  const run = SHELL_SYNTAX.test(startCommand) ? startCommand : `exec ${startCommand}`;
  const buildScript = input.buildCommand ?? (hasBuildScript ? runScriptCommand(pm, "build").join(" ") : null);

  return [
    "# Generated by ShipFlow (node strategy). Do not edit; set build.strategy: dockerfile to use your own.",
    `FROM ${base} AS build`,
    "WORKDIR /app",
    "RUN corepack enable",
    `COPY ${MANIFESTS} ./`,
    `RUN ${installLines(pm, false)}`,
    "COPY . .",
    ...(buildScript ? [`RUN ${buildScript}`] : []),
    "RUN rm -rf node_modules",
    "",
    `FROM ${base}`,
    "ENV NODE_ENV=production",
    "ENV PATH=/app/node_modules/.bin:$PATH",
    "WORKDIR /app",
    "RUN corepack enable",
    `COPY ${MANIFESTS} ./`,
    `RUN ${installLines(pm, true)}`,
    "COPY --from=build /app ./",
    "RUN chown -R node:node /app",
    "USER node",
    `EXPOSE ${port}`,
    `CMD ${JSON.stringify(["sh", "-c", run])}`,
    "",
  ].join("\n");
}

/** Node major from package.json engines.node, within the supported range; default 22. */
export function nodeMajorOf(packageJson: PackageJson): number {
  const engines = packageJson.engines;
  const range = typeof engines === "object" && engines !== null && "node" in engines ? engines.node : undefined;
  const major = typeof range === "string" ? Number(/(\d+)/.exec(range)?.[1]) : NaN;

  return major >= 20 && major <= 24 ? major : 22;
}

interface Built {
  packageJson: PackageJson;
  packageManager: PackageManagerInfo;
  startCommand: string;
  hasBuildScript: boolean;
}

function requireSandbox(sandbox: SandboxHandle | null): SandboxHandle {
  if (!sandbox) {
    throw new Error("The node strategy requires a build sandbox");
  }

  return sandbox;
}

export function resolveStartCommand(packageJson: PackageJson, runtimeStart: string | undefined): string {
  const start = runtimeStart?.trim() || packageJson.scripts?.start?.trim();

  if (!start) {
    throw new Error(
      'No start command: add a "start" script to package.json or set runtime.start in shipflow.yml'
    );
  }

  return start;
}

export interface NodeStrategyOptions {
  run?: RunDocker;
}

export function createNodeStrategy(options: NodeStrategyOptions = {}): BuildStrategy {
  return {
    id: "node",
    artifactType: "image",
    usesSandbox: true,

    async build(input: StrategyInput, sandbox: SandboxHandle | null): Promise<Built> {
      const box = requireSandbox(sandbox);
      const { build, log, workspacePath } = input;
      const packageJson = await readPackageJson(workspacePath);
      const startCommand = resolveStartCommand(packageJson, input.runtime?.start);
      const packageManager = await detectPackageManager(workspacePath, packageJson);
      const hasBuildScript = Boolean(packageJson.scripts?.build);

      await log(`Sandbox: ${box.kind}`);

      if (build.install === "none") {
        await log("Dependency install skipped (build.install: none)");
      } else {
        await log(
          `Package manager: ${packageManager.name} ` +
            (packageManager.hasLockfile ? "(lockfile found, reproducible install)" : "(no lockfile, install is not reproducible)")
        );
        const install = await box.exec("Dependency install", installCommand(packageManager), {
          timeoutMs: config.installTimeoutMs,
        });
        await log(`Dependency install output:\n${install.output}`);
      }

      await box.disableNetwork();

      if (build.command === "auto" && !hasBuildScript) {
        await log('No "build" script in package.json; nothing to build');
      } else {
        const command = build.command === "auto" ? runScriptCommand(packageManager, "build") : ["sh", "-c", build.command];
        await log(`Build command: ${build.command === "auto" ? packageJson.scripts?.build : build.command}`);
        const result = await box.exec("Build", command, { timeoutMs: config.buildTimeoutMs });
        await log(`Build output:\n${result.output}`);
      }

      return { packageJson, packageManager, startCommand, hasBuildScript };
    },

    async test(input, sandbox, built) {
      const { packageJson, packageManager } = built as Built;
      const result = await testRelease({
        releaseId: input.releaseId,
        workspacePath: input.workspacePath,
        sandbox: requireSandbox(sandbox),
        packageJson,
        packageManager,
        testConfig: input.build.test,
        log: input.log,
      });

      return { testStatus: result.testStatus };
    },

    async produce(input, _sandbox, built): Promise<LocalArtifact> {
      assertImageBuildsEnabled();

      if (!input.runtime) {
        throw new Error("runtime.port is required to build a container image");
      }

      const { packageJson, packageManager, startCommand, hasBuildScript } = built as Built;
      // The image build repeats what the sandbox build ran.
      const explicit = input.build.command !== "auto" ? input.build.command : undefined;
      const dockerfile = generateNodeDockerfile({
        packageManager,
        startCommand,
        port: input.runtime.port,
        hasBuildScript,
        ...(explicit ? { buildCommand: explicit } : {}),
        nodeMajor: nodeMajorOf(packageJson),
      });
      const dockerfilePath = path.join(input.scratchDir, "Dockerfile");

      await fs.mkdir(input.scratchDir, { recursive: true });
      await fs.writeFile(dockerfilePath, dockerfile);
      // BuildKit reads <Dockerfile>.dockerignore next to the Dockerfile.
      await fs.writeFile(`${dockerfilePath}.dockerignore`, NODE_DOCKERIGNORE);
      await input.log(`Generated Dockerfile:\n${dockerfile}`);

      const image = await buildImage({
        releaseId: input.releaseId,
        contextDir: input.workspacePath,
        dockerfilePath,
        port: input.runtime.port,
        scratchDir: input.scratchDir,
        log: input.log,
        ...(options.run ? { run: options.run } : {}),
      });

      return { type: "image", ...image };
    },
  };
}

export const nodeStrategy: BuildStrategy = createNodeStrategy();
